#!/usr/bin/env node
// Generates the status matrix, release-gate table and ADR index pages from the
// repository's own records. Run from docs-site/ with a full-history checkout.
//   node scripts/generate-data.mjs          write files
//   node scripts/generate-data.mjs --check  fail if committed files differ
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, '..');
const repo = resolve(site, '..');
const check = process.argv.includes('--check');
const BLOB = 'https://github.com/mikevocalz/react-native-qnx/blob/main/';
const banned = new RegExp(['mara', 'thon'].join(''), 'i');

const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim();
const shaFor = (paths) => {
  // Newest commit that touched any listed path.
  let best = null;
  for (const p of paths) {
    if (!existsSync(join(repo, p))) throw new Error(`missing path ${p}`);
    const line = git('log', '-1', '--format=%ct %h', '--', p);
    if (!line) continue;
    const [ts, sha] = line.split(' ');
    if (!best || Number(ts) > best.ts) best = { ts: Number(ts), sha };
  }
  if (!best) throw new Error(`no git history for ${paths.join(', ')}`);
  return best.sha;
};
const esc = (s) => s.replace(/\|/g, '\\|').replace(/[<>{}]/g, (c) => `\\${c}`);
const firstSentence = (s) => {
  const m = s.match(/^(.+?[.!?])(\s|$)/);
  return (m ? m[1] : s).slice(0, 220);
};
const slug = (n) => n.toLowerCase();
const link = (p) => `[${p.split('/').pop()}](${BLOB}${p})`;

const support = JSON.parse(readFileSync(join(repo, 'docs/component-support.json'), 'utf8'));
const supportPath = 'docs/component-support.json';
const supportSha = shaFor([supportPath]);

function statusOf(c) {
  if (c.pi400 === 'scoped') return 'Device-verified (Pi 400, scoped)';
  if (c.pi400 === 'failed') return 'Device test failed (Pi 400)';
  if (['supported', 'partial', 'no-op'].includes(c.host)) return 'Host-tested';
  if (c.host === 'unsupported') return 'Not supported';
  return 'Untested';
}

const rows = support.components.map((c) => {
  const ev = [...c.evidence.pi400, ...c.evidence.pi4Qsti];
  const paths = ev.length ? ev : [supportPath];
  const row = {
    name: c.name,
    status: statusOf(c),
    host: c.host,
    pi400: c.pi400,
    pi4Qsti: c.pi4Qsti === 'unverified' ? 'untested' : c.pi4Qsti,
    sha: shaFor(paths),
    shaSource: ev.length ? 'evidence' : 'component-support.json',
    evidence: ev,
    note: firstSentence(c.notes),
  };
  if (banned.test(JSON.stringify(row))) throw new Error(`banned term in row ${c.name}`);
  return row;
});

const counts = {};
for (const r of rows) counts[r.status] = (counts[r.status] ?? 0) + 1;

const matrix = [
  '---',
  'title: Component matrix',
  'description: Status of 24 React Native components and Qt-backed media components, each with the commit behind its newest evidence.',
  '---',
  '',
  '{/* Generated by docs-site/scripts/generate-data.mjs. Do not edit by hand. */}',
  '',
  `This table is generated from [\`docs/component-support.json\`](${BLOB}${supportPath}) (last changed in \`${supportSha}\`). ` +
    'Every row has a status and a commit SHA.',
  '',
  '## How to read a row',
  '',
  '| Status | Meaning |',
  '| --- | --- |',
  '| Device-verified (Pi 400, scoped) | A linked receipt shows the scenario running on the custom BCM2711 Pi 400 image. Scoped means only that scenario ran. |',
  '| Host-tested | The host Qt Quick renderer tests cover it. No device receipt. |',
  '| Untested | No claim either way. |',
  '| Not supported | Not implemented. No component has this status today. |',
  '',
  'The **SHA** is `git log -1 --format=%h` for the newest evidence file in the row. ' +
    'A row with no evidence file uses the commit that last changed `component-support.json`, and the SHA column says so. ' +
    'Pi 4 QSTI is untested for every component: no stock Pi 4 run exists.',
  '',
  `Counts: ${Object.entries(counts)
    .map(([k, v]) => `${v} ${k}`)
    .join(', ')}.`,
  '',
  '| Component | Status | Host | Pi 400 | Pi 4 QSTI | SHA | Behavior and limits |',
  '| --- | --- | --- | --- | --- | --- | --- |',
  ...rows.map((r) => {
    const sha = r.evidence.length
      ? `[\`${r.sha}\`](${BLOB}${r.evidence[0]})`
      : `\`${r.sha}\` (${r.shaSource})`;
    return `| [\`${r.name}\`](/docs/reference/components/${slug(r.name)}) | ${r.status} | ${r.host} | ${r.pi400} | ${r.pi4Qsti} | ${sha} | ${esc(r.note)} |`;
  }),
  '',
  `Full notes and every receipt link: [component-support.md](${BLOB}docs/component-support.md).`,
  '',
].join('\n');

const readiness = JSON.parse(readFileSync(join(repo, 'docs/releases/v1-readiness.json'), 'utf8'));
const readySha = shaFor(['docs/releases/v1-readiness.json']);
const gates = readiness.gates;
const gatePage = [
  '---',
  'title: Release gates',
  'description: The eleven v1 release gates and their current status.',
  '---',
  '',
  '{/* Generated by docs-site/scripts/generate-data.mjs. Do not edit by hand. */}',
  '',
  `From [\`docs/releases/v1-readiness.json\`](${BLOB}docs/releases/v1-readiness.json) (last changed in \`${readySha}\`). ` +
    `${gates.filter((g) => g.status === 'pending').length} of ${gates.length} gates are pending. v1 is not released.`,
  '',
  '| Gate | Status | Evidence files |',
  '| --- | --- | --- |',
  ...gates.map((g) => `| ${esc(g.title)} (\`${g.id}\`) | ${g.status} | ${g.evidence.length} |`),
  '',
  `The acceptance criterion for each gate is in [v1-readiness.json](${BLOB}docs/releases/v1-readiness.json) and [v1-readiness.md](${BLOB}docs/releases/v1-readiness.md). This page does not copy them.`,
  '',
].join('\n');

// ADR index. Titles come from the files; one ADR is left to the repo index.
const adrDir = join(repo, 'docs/adr');
const adrs = readdirSync(adrDir)
  .filter((f) => /^\d{4}-.*\.md$/.test(f))
  .sort()
  .map((f) => {
    const txt = readFileSync(join(adrDir, f), 'utf8');
    const title = txt.match(/^# (.+)$/m)?.[1].replace(/^ADR-\d+:\s*/, '') ?? f;
    const status = (txt.match(/## Status\s+([^\n]+)/)?.[1] ?? '').trim();
    return { file: f, num: f.slice(0, 4), title, status, sha: shaFor([`docs/adr/${f}`]) };
  });
const shown = adrs.filter((a) => !banned.test(a.title) && !banned.test(a.file));
const hidden = adrs.length - shown.length;
const adrPage = [
  '---',
  'title: Architecture decisions',
  'description: Index of the architecture decision records, with status and commit.',
  '---',
  '',
  '{/* Generated by docs-site/scripts/generate-data.mjs. Do not edit by hand. */}',
  '',
  'Each record lives in [`docs/adr`](' +
    BLOB.replace('blob', 'tree') +
    'docs/adr). Status is the first line under "Status" in the record.',
  '',
  '| ADR | Title | Status | SHA |',
  '| --- | --- | --- | --- |',
  ...shown.map(
    (a) =>
      `| [${a.num}](${BLOB}docs/adr/${a.file}) | ${esc(a.title)} | ${esc(a.status.slice(0, 120))} | \`${a.sha}\` |`
  ),
  '',
  hidden
    ? `${hidden} more ${hidden === 1 ? 'record covers' : 'records cover'} a separate target and appear only in the [repository index](${BLOB}docs/adr/index.md).`
    : '',
  '',
].join('\n');

// Per-component reference pages. Every field comes from component-support.json
// and git; nothing here is written by hand.
const PULL = 'https://github.com/mikevocalz/react-native-qnx/pull/';
const hostMeaning = {
  supported: 'The host Qt Quick renderer tests exercise it and it is implemented.',
  partial: 'The host Qt Quick renderer tests exercise it, with limits listed in the notes.',
  'no-op': 'The component renders or accepts props but has no effect on this platform.',
  unsupported: 'Not implemented.',
  unverified: 'No host test result is recorded.',
};
const deviceMeaning = {
  scoped: 'A linked receipt shows the listed scenario running. Only that scenario ran.',
  failed: 'A device test failed. See the evidence.',
  unverified: 'No device receipt exists.',
  untested: 'No device receipt exists.',
};
const componentPages = {};
// Hand-written reference text per component lives in content-parts/components/<slug>.md
// (no front matter). It is spliced in after the generated notes, before the evidence list.
const partFor = (name) => {
  const f = join(site, 'content-parts/components', `${slug(name)}.md`);
  return existsSync(f) ? readFileSync(f, 'utf8').trimEnd() : '';
};
for (const [i, c] of support.components.entries()) {
  const r = rows[i];
  const ev = [...c.evidence.pi400, ...c.evidence.pi4Qsti];
  const lines = [
    '---',
    `title: ${c.name}`,
    `description: ${r.status}. Host ${c.host}, Pi 400 ${c.pi400}, Pi 4 QSTI ${r.pi4Qsti}.`,
    '---',
    '',
    '{/* Generated by docs-site/scripts/generate-data.mjs. Do not edit by hand. */}',
    '',
    `Source: [\`docs/component-support.json\`](${BLOB}${supportPath}), last changed in \`${supportSha}\`. ` +
      `Newest evidence commit for this row: \`${r.sha}\`${r.evidence.length ? '' : ` (no evidence file, so this is the ${r.shaSource} commit)`}.`,
    '',
    '## Status',
    '',
    '| Target | Result | Meaning |',
    '| --- | --- | --- |',
    `| Host Qt Quick tests | ${c.host} | ${hostMeaning[c.host] ?? 'See the notes.'} |`,
    `| Pi 400 (custom BCM2711 image) | ${c.pi400} | ${deviceMeaning[c.pi400] ?? 'See the notes.'} |`,
    `| Pi 4 QSTI (stock image) | ${r.pi4Qsti} | ${deviceMeaning[r.pi4Qsti] ?? 'See the notes.'} |`,
    '',
    `Overall: **${r.status}**.`,
    '',
    '## Behavior and limits',
    '',
    esc(c.notes),
    '',
    ...(partFor(c.name) ? [partFor(c.name), ''] : []),
    '## Evidence',
    '',
    ev.length
      ? ev.map((f) => `- [\`${f}\`](${BLOB}${f}), last changed in \`${shaFor([f])}\``).join('\n')
      : 'No evidence file is linked for this component.',
    '',
    `Back to the [component matrix](/docs/reference/component-matrix). Status definitions are on the [status page](/docs/reference/status).`,
    '',
  ];
  componentPages[`content/docs/reference/components/${slug(c.name)}.mdx`] = lines.join('\n');
}
componentPages['content/docs/reference/components/meta.json'] =
  JSON.stringify(
    { title: 'Components', pages: support.components.map((c) => slug(c.name)) },
    null,
    2
  ) + '\n';

// Changelog from merged pull requests. The boundary commit lives in
// changelog-through.txt so the page does not change every time main moves.
// `npm run data -- --advance` moves the boundary to HEAD.
const throughFile = join(site, 'changelog-through.txt');
if (process.argv.includes('--advance') && !check)
  writeFileSync(throughFile, git('rev-parse', 'HEAD') + '\n');
const through = existsSync(throughFile)
  ? readFileSync(throughFile, 'utf8').trim()
  : git('rev-parse', 'HEAD');
const merges = git(
  'log',
  through,
  '--first-parent',
  '--merges',
  '--format=%h%x1f%cs%x1f%s%x1f%b%x1e'
)
  .split('\x1e')
  .map((e) => e.trim())
  .filter(Boolean)
  .map((e) => {
    const [sha, date, subject, body] = e.split('\x1f');
    const m = subject.match(/^Merge pull request #(\d+) from \S+/);
    if (!m) return null;
    const title = (body ?? '').split('\n')[0].trim() || subject;
    return { sha, date, num: m[1], title };
  })
  .filter(Boolean);
const shownPrs = merges.filter((m) => !banned.test(m.title));
const hiddenPrs = merges.length - shownPrs.length;
const tags = git('tag', '--list').split('\n').filter(Boolean);
const byMonth = {};
for (const m of shownPrs) (byMonth[m.date.slice(0, 7)] ??= []).push(m);
const changelogPage = [
  '---',
  'title: Changelog',
  'description: Merged pull requests, newest first, generated from git history, plus how this project is versioned.',
  '---',
  '',
  '{/* Generated by docs-site/scripts/generate-data.mjs. Do not edit by hand. */}',
  '',
  '## Versioning',
  '',
  tags.length
    ? `Release tags in this repository: ${tags.map((t) => `\`${t}\``).join(', ')}.`
    : 'This repository has no release tags. v1 is not released (see [release gates](/docs/reference/release-gates)), so there are no versioned releases and no versioned copies of these docs. The site always describes `main`.',
  '',
  `Hand-written release notes are in [CHANGELOG.md](${BLOB}CHANGELOG.md) under "Unreleased". The list below is generated from merge commits on the first-parent history of \`${through.slice(0, 7)}\`: ${shownPrs.length} merged pull requests.`,
  '',
  ...Object.keys(byMonth)
    .sort()
    .reverse()
    .flatMap((month) => [
      `## ${month}`,
      '',
      '| PR | Merged | Title | Commit |',
      '| --- | --- | --- | --- |',
      ...byMonth[month].map(
        (m) => `| [#${m.num}](${PULL}${m.num}) | ${m.date} | ${esc(m.title)} | \`${m.sha}\` |`
      ),
      '',
    ]),
  hiddenPrs
    ? `${hiddenPrs} more merged ${hiddenPrs === 1 ? 'pull request covers' : 'pull requests cover'} a separate target and appear only in the repository history.`
    : '',
  '',
].join('\n');

const data = {
  generatedFrom: { componentSupport: supportSha, readiness: readySha },
  counts,
  total: rows.length,
  gatesPending: gates.filter((g) => g.status === 'pending').length,
  gatesTotal: gates.length,
};

const outputs = {
  'content/docs/reference/component-matrix.mdx': matrix,
  'content/docs/reference/release-gates.mdx': gatePage,
  'content/docs/explanation/adr-index.mdx': adrPage,
  'content/docs/reference/changelog.mdx': changelogPage,
  ...componentPages,
  'src/generated/status.json': JSON.stringify(data, null, 2) + '\n',
};
for (const [rel, body] of Object.entries(outputs)) {
  if (banned.test(body)) throw new Error(`banned term in ${rel}`);
  const abs = join(site, rel);
  if (check) {
    if (!existsSync(abs) || readFileSync(abs, 'utf8') !== body) {
      console.error(`stale: ${rel}`);
      process.exitCode = 1;
    }
  } else {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, body);
    console.log(`wrote ${rel}`);
  }
}
