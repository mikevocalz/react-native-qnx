#!/usr/bin/env node
// Per-package capability table for Expo SDK 58, generated from
// docs/expo-delivery/sdk58-support.json. Never edit the output by hand.
//
//   node scripts/expo-capability-table.mjs --write   regenerate the Markdown file
//   node scripts/expo-capability-table.mjs --check   fail when the file differs
//
// docs-site/scripts/generate-data.mjs imports renderCapabilityTable() for the
// site page, so the site and the repository file come from one function.
//
// The capability words describe published package contents plus the repository's
// own port packages. None of them is a device run.

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SUPPORT_FILE = path.join(root, 'docs/expo-delivery/sdk58-support.json');
export const TABLE_FILE = path.join(root, 'docs/expo-delivery/sdk58-capability-table.md');

/**
 * Support-list status to capability. Every status in sdk58-support.json has an
 * entry; capabilityOf() throws on one that does not, so a new classifier status
 * cannot reach the table unlabelled.
 */
export const CAPABILITY = Object.freeze({
  platform: {
    label: 'works',
    meaning:
      'Provided on QNX by this repository, or the package declares a qnx platform in expo-module.config.json.',
  },
  'qnx-native': {
    label: 'works',
    meaning:
      'Provided on QNX by this repository, or the package declares a qnx platform in expo-module.config.json.',
  },
  'js-only': {
    label: 'JS-only',
    meaning: 'Publishes no native code. It bundles as JavaScript and needs no QNX port.',
  },
  partial: {
    label: 'shim',
    meaning:
      'Upstream native code is iOS and Android. A package in this repository supplies a QNX replacement for part of the API; the reason column says which part.',
  },
  unsupported: {
    label: 'unsupported',
    meaning:
      'Native code for iOS or Android only, and no QNX port is recorded for it in the support list (the ports are the `partial` rows).',
  },
  'host-tooling': {
    label: 'host tooling',
    meaning: 'Runs on the development host. It is not part of a QNX app bundle.',
  },
  'no-op': {
    label: 'not bundled',
    meaning: 'Web-only or build-time package. It is not part of a QNX app bundle.',
  },
});

/** Order of the groups in the output. */
const ORDER = ['works', 'JS-only', 'shim', 'unsupported', 'host tooling', 'not bundled'];

/** @param {string} status */
export function capabilityOf(status) {
  const entry = /** @type {Record<string, {label: string, meaning: string}>} */ (CAPABILITY)[
    status
  ];
  if (!entry) throw new Error(`No capability label for support status "${status}".`);
  return entry;
}

/** @param {string} text */
const esc = (text) => text.replace(/\|/g, '\\|').replace(/[<>{}]/g, (c) => `\\${c}`);

/**
 * @param {{expoVersion: string, packages: Array<{name: string, resolved: string, status: string, reason: string}>}} list
 * @param {{comment: (text: string) => string}} options
 */
export function renderCapabilityTable(list, options) {
  const rows = list.packages.map((p) => ({ ...p, capability: capabilityOf(p.status).label }));
  const counts = ORDER.map((label) => [label, rows.filter((r) => r.capability === label).length]);
  const sorted = [...rows].sort(
    (a, b) =>
      ORDER.indexOf(a.capability) - ORDER.indexOf(b.capability) || a.name.localeCompare(b.name)
  );
  const meanings = new Map();
  for (const entry of Object.values(CAPABILITY)) meanings.set(entry.label, entry.meaning);
  return [
    options.comment('Generated by scripts/expo-capability-table.mjs. Do not edit by hand.'),
    '',
    `Expo SDK 58 (expo ${list.expoVersion}), ${rows.length} packages. Generated from \`docs/expo-delivery/sdk58-support.json\`, which classifies each package from its published files. No row is a device run: a package marked \`works\` or \`shim\` has not been shown running on a QNX board by this table.`,
    '',
    `Counts: ${counts.map(([label, n]) => `${n} ${label}`).join(', ')}.`,
    '',
    '| Capability | Meaning |',
    '| --- | --- |',
    ...ORDER.map((label) => `| ${label} | ${esc(meanings.get(label))} |`),
    '',
    '| Package | Version | Capability | Reason |',
    '| --- | --- | --- | --- |',
    ...sorted.map((r) => `| \`${r.name}\` | ${r.resolved} | ${r.capability} | ${esc(r.reason)} |`),
    '',
  ].join('\n');
}

/** @returns {Promise<string>} */
export async function repositoryTable() {
  const list = JSON.parse(await readFile(SUPPORT_FILE, 'utf8'));
  return renderCapabilityTable(list, { comment: (text) => `<!-- ${text} -->` });
}

async function main() {
  const mode = process.argv[2];
  if (mode === '--write') {
    await writeFile(TABLE_FILE, await repositoryTable());
    console.log(`Wrote ${path.relative(root, TABLE_FILE)}.`);
  } else if (mode === '--check') {
    const expected = await repositoryTable();
    const actual = await readFile(TABLE_FILE, 'utf8').catch(() => null);
    if (actual !== expected) {
      console.error(
        'Expo SDK 58 capability table is stale. Regenerate: node scripts/expo-capability-table.mjs --write'
      );
      process.exitCode = 1;
    } else console.log('Expo SDK 58 capability table matches sdk58-support.json.');
  } else {
    console.error('Use --write or --check.');
    process.exitCode = 2;
  }
}

if (import.meta.main) await main();
