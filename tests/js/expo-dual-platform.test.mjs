import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import path from 'node:path';

const require = createRequire(import.meta.url);
const api = require('../../packages/expo-qnx-autolinking/src/index.js');
const root = await mkdtemp(path.join(tmpdir(), 'rnqnx-dual-expo-'));
let checks = 0;
/** @param {unknown} actual @param {unknown} expected */
function equal(actual, expected) { assert.deepEqual(actual, expected); checks += 1; }
try {
  for (const platform of ['qnx', 'marathon']) {
    await mkdir(path.join(root, platform));
    await writeFile(path.join(root, platform, 'CMakeLists.txt'), `add_library(fixture_${platform} INTERFACE)\n`);
  }
  const config = {
    platforms: ['qnx', 'marathon'],
    qnx: { target: 'fixture_qnx', modules: ['QnxCounter'], cmakeListsPath: 'qnx/CMakeLists.txt' },
    marathon: { target: 'fixture_marathon', modules: ['MarathonCounter'], cmakeListsPath: 'marathon/CMakeLists.txt' },
  };
  const results = {
    shared: { path: root, version: '1.0.0', config: { toJSON: () => config } },
    apple: { path: root, version: '1.0.0', config: { platforms: ['apple'] } },
  };
  const qnx = api.resolveQnxSearchResults(results);
  const marathon = api.resolveExpoSearchResults(results, 'marathon');
  equal(api.resolveExpoSearchResults(results), qnx);
  equal(qnx.length, 1); equal(marathon.length, 1);
  equal(qnx[0].target, 'fixture_qnx'); equal(marathon[0].target, 'fixture_marathon');
  equal(marathon[0].modules, ['MarathonCounter']);
  equal(qnx[0].modules, ['QnxCounter']);
  const qnxCmake = api.generateQnxCMake(qnx);
  equal(api.generateExpoPlatformCMake(qnx, 'qnx'), qnxCmake);
  equal(qnxCmake, [
    '# Generated by @rn-qnx/expo-qnx-autolinking. Do not edit.',
    'set(RNQNX_EXPO_QNX_MODULE_TARGETS "")', '',
    `add_subdirectory("${path.join(root, 'qnx')}" "\${CMAKE_BINARY_DIR}/expo-qnx/shared")`,
    'if(NOT TARGET fixture_qnx)',
    '  message(FATAL_ERROR "QNX Expo module shared did not define target fixture_qnx")',
    'endif()', 'list(APPEND RNQNX_EXPO_QNX_MODULE_TARGETS fixture_qnx)', '', '',
  ].join('\n'));
  assert.match(api.generateExpoPlatformCMake(marathon, 'marathon'), /RNQNX_EXPO_MARATHON_MODULE_TARGETS/); checks += 1;
  assert.doesNotMatch(api.generateExpoPlatformCMake(marathon, 'marathon'), /fixture_qnx|expo-qnx\/shared/); checks += 1;
  const qnxOnly = { one: { path: root, version: '1.0.0', config: { platforms: ['qnx'], qnx: config.qnx } } };
  equal(api.resolveExpoSearchResults(qnxOnly, 'marathon'), []);
  const missingNative = { one: { path: root, version: '1.0.0', config: { platforms: ['marathon'], qnx: config.qnx } } };
  assert.throws(() => api.resolveExpoSearchResults(missingNative, 'marathon'), /no marathon config object/); checks += 1;
  for (const platform of ['android', '', '__proto__', 'QNX']) {
    assert.throws(() => api.resolveExpoSearchResults(results, /** @type {any} */ (platform)), /qnx or marathon/); checks += 1;
    assert.throws(() => api.generateExpoPlatformCMake([], /** @type {any} */ (platform)), /qnx or marathon/); checks += 1;
    await assert.rejects(api.findExpoModulesForPlatform(root, /** @type {any} */ (platform)), /qnx or marathon/); checks += 1;
  }
  assert.throws(() => api.generateExpoPlatformCMake([qnx[0], qnx[0]]), /Duplicate/); checks += 1;
  for (const target of ['x)\nmessage(FATAL_ERROR bad)', 'x;y', '']) {
    assert.throws(() => api.generateExpoPlatformCMake([{ ...qnx[0], target }]), /Invalid/); checks += 1;
  }
  assert.throws(() => api.generateExpoPlatformCMake([{ ...qnx[0], binaryName: '../escape' }]), /Invalid/); checks += 1;
  equal(api.resolveExpoSearchResults({ one: { ...results.shared, config: { rawConfig: config } } }, 'marathon')[0].target, 'fixture_marathon');
  console.log(`expo-dual-platform: ${checks} checks passed (descriptor/generator host fixtures).`);
} finally {
  await rm(root, { recursive: true, force: true });
}
