'use strict';

const fs = require('fs');
const path = require('path');
const { createRequire } = require('module');

function loadExpoAutolinking() {
  const expoManifest = require.resolve('expo/package.json');
  const expoRequire = createRequire(expoManifest);
  return expoRequire('expo-modules-autolinking/exports');
}

function rawConfigForRevision(revision) {
  const config = revision?.config;
  if (!config) return null;
  if (typeof config.toJSON === 'function') return config.toJSON();
  if (config.rawConfig && typeof config.rawConfig === 'object') return config.rawConfig;
  return config;
}

function sanitizeBinaryName(packageName) {
  return packageName.replace(/[^A-Za-z0-9_.-]/g, '_');
}

function resolveQnxSearchResults(searchResults) {
  const descriptors = [];

  for (const [packageName, revision] of Object.entries(searchResults || {})) {
    const raw = rawConfigForRevision(revision);
    if (!raw || !Array.isArray(raw.platforms) || !raw.platforms.includes('qnx')) {
      continue;
    }

    const qnx = raw.qnx;
    if (!qnx || typeof qnx !== 'object') {
      throw new Error(
        `Expo module ${packageName} declares platform "qnx" but has no qnx config object.`
      );
    }
    if (typeof qnx.target !== 'string' || qnx.target.length === 0) {
      throw new Error(`Expo module ${packageName} must declare qnx.target for CMake autolinking.`);
    }

    const packageRoot = revision.path;
    const cmakeListsPath =
      typeof qnx.cmakeListsPath === 'string' && qnx.cmakeListsPath.length > 0
        ? qnx.cmakeListsPath
        : 'CMakeLists.txt';
    const modules = Array.isArray(qnx.modules)
      ? qnx.modules.filter((name) => typeof name === 'string' && name.length > 0)
      : [];

    descriptors.push({
      packageName,
      packageRoot,
      version: revision.version,
      cmakeListsPath,
      target: qnx.target,
      modules,
      binaryName: sanitizeBinaryName(packageName),
    });
  }

  return descriptors.sort((a, b) => a.packageName.localeCompare(b.packageName));
}

async function findQnxExpoModules(projectRoot = process.cwd()) {
  const { findModulesAsync } = loadExpoAutolinking();
  const searchResults = await findModulesAsync({
    projectRoot,
    platform: 'qnx',
  });
  return resolveQnxSearchResults(searchResults);
}

function quoteCMake(value) {
  return value.replace(/\\/g, '/').replace(/"/g, '\\"');
}

function generateQnxCMake(descriptors) {
  const lines = [
    '# Generated by @rn-qnx/expo-qnx-autolinking. Do not edit.',
    'set(RNQNX_EXPO_QNX_MODULE_TARGETS "")',
    '',
  ];

  for (const descriptor of descriptors) {
    const cmakeFile = path.resolve(descriptor.packageRoot, descriptor.cmakeListsPath);
    const moduleDir = path.dirname(cmakeFile);
    if (!fs.existsSync(cmakeFile)) {
      throw new Error(
        `QNX Expo module ${descriptor.packageName} is missing ${descriptor.cmakeListsPath}`
      );
    }

    lines.push(
      `add_subdirectory("${quoteCMake(moduleDir)}" "\${CMAKE_BINARY_DIR}/expo-qnx/${descriptor.binaryName}")`
    );
    lines.push(
      `if(NOT TARGET ${descriptor.target})`,
      `  message(FATAL_ERROR "QNX Expo module ${descriptor.packageName} did not define target ${descriptor.target}")`,
      'endif()'
    );
    lines.push(`list(APPEND RNQNX_EXPO_QNX_MODULE_TARGETS ${descriptor.target})`, '');
  }

  return `${lines.join('\n')}\n`;
}

module.exports = {
  findQnxExpoModules,
  generateQnxCMake,
  resolveQnxSearchResults,
};
