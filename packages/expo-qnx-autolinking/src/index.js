'use strict';

const fs = require('fs');
const path = require('path');
const { createRequire } = require('module');

function nativePlatform(platform = 'qnx') {
  if (platform !== 'qnx' && platform !== 'marathon') {
    throw new Error('Expo native platform must be qnx or marathon.');
  }
  return platform;
}
function loadExpoAutolinking() {
  const expoManifest = require.resolve('expo/package.json');
  const expoRequire = createRequire(expoManifest);
  return expoRequire('expo-modules-autolinking/exports');
}
function rawConfigForRevision(revision) {
  const config = revision?.config;
  if (!config) return null;
  if (typeof config.toJSON === 'function') return config.toJSON();
  if (config.rawConfig && typeof config.rawConfig === 'object') return config.rawConfig;
  return config;
}
function sanitizeBinaryName(packageName) {
  return packageName.replace(/[^A-Za-z0-9_.-]/g, '_');
}

function resolveExpoSearchResults(searchResults, requestedPlatform = 'qnx') {
  const platform = nativePlatform(requestedPlatform);
  const descriptors = [];
  for (const [packageName, revision] of Object.entries(searchResults || {})) {
    const raw = rawConfigForRevision(revision);
    if (!raw || !Array.isArray(raw.platforms) || !raw.platforms.includes(platform)) continue;
    const native = raw[platform];
    if (!native || typeof native !== 'object' || Array.isArray(native)) {
      throw new Error(
        `Expo module ${packageName} declares platform "${platform}" but has no ${platform} config object.`
      );
    }
    if (typeof native.target !== 'string' || native.target.length === 0) {
      throw new Error(
        `Expo module ${packageName} must declare ${platform}.target for CMake autolinking.`
      );
    }
    const cmakeListsPath =
      typeof native.cmakeListsPath === 'string' && native.cmakeListsPath.length > 0
        ? native.cmakeListsPath
        : 'CMakeLists.txt';
    const modules = Array.isArray(native.modules)
      ? native.modules.filter((name) => typeof name === 'string' && name.length > 0)
      : [];
    descriptors.push({
      packageName,
      packageRoot: revision.path,
      version: revision.version,
      cmakeListsPath,
      target: native.target,
      modules,
      binaryName: sanitizeBinaryName(packageName),
    });
  }
  return descriptors.sort((a, b) => a.packageName.localeCompare(b.packageName));
}

function resolveQnxSearchResults(searchResults) {
  return resolveExpoSearchResults(searchResults, 'qnx');
}
async function findExpoModulesForPlatform(projectRoot = process.cwd(), requestedPlatform = 'qnx') {
  const platform = nativePlatform(requestedPlatform);
  const { findModulesAsync } = loadExpoAutolinking();
  const searchResults = await findModulesAsync({ projectRoot, platform });
  return resolveExpoSearchResults(searchResults, platform);
}
async function findQnxExpoModules(projectRoot = process.cwd()) {
  return findExpoModulesForPlatform(projectRoot, 'qnx');
}
function quoteCMake(value) {
  return value.replace(/\\/g, '/').replace(/"/g, '\\"');
}
function generateExpoPlatformCMake(descriptors, requestedPlatform = 'qnx') {
  const platform = nativePlatform(requestedPlatform);
  const variable = `RNQNX_EXPO_${platform.toUpperCase()}_MODULE_TARGETS`;
  const lines = [
    '# Generated by @rn-qnx/expo-qnx-autolinking. Do not edit.',
    `set(${variable} "")`,
    '',
  ];
  const targets = new Set();
  const binaries = new Set();
  for (const descriptor of descriptors) {
    if (
      !/^[A-Za-z_][A-Za-z0-9_.+-]*$/.test(descriptor.target) ||
      !/^[A-Za-z0-9_.-]+$/.test(descriptor.binaryName) ||
      descriptor.binaryName === '.' ||
      descriptor.binaryName === '..'
    ) {
      throw new Error('Invalid Expo native CMake target or binary directory.');
    }
    if (targets.has(descriptor.target) || binaries.has(descriptor.binaryName)) {
      throw new Error('Duplicate Expo native target or binary directory.');
    }
    targets.add(descriptor.target);
    binaries.add(descriptor.binaryName);
    const cmakeFile = path.resolve(descriptor.packageRoot, descriptor.cmakeListsPath);
    const moduleDir = path.dirname(cmakeFile);
    if (/[\x00-\x1f";$]/.test(moduleDir + descriptor.packageName)) {
      throw new Error('Unsupported CMake metacharacters in Expo native module identity/path.');
    }
    if (!fs.existsSync(cmakeFile)) {
      throw new Error(
        `QNX Expo module ${descriptor.packageName} is missing ${descriptor.cmakeListsPath}`
      );
    }
    lines.push(
      `add_subdirectory("${quoteCMake(moduleDir)}" "\${CMAKE_BINARY_DIR}/expo-${platform}/${descriptor.binaryName}")`
    );
    lines.push(
      `if(NOT TARGET ${descriptor.target})`,
      `  message(FATAL_ERROR "QNX Expo module ${descriptor.packageName} did not define target ${descriptor.target}")`,
      'endif()'
    );
    lines.push(`list(APPEND ${variable} ${descriptor.target})`, '');
  }
  return `${lines.join('\n')}\n`;
}
function generateQnxCMake(descriptors) {
  return generateExpoPlatformCMake(descriptors, 'qnx');
}

module.exports = {
  findQnxExpoModules,
  generateQnxCMake,
  resolveQnxSearchResults,
  findExpoModulesForPlatform,
  generateExpoPlatformCMake,
  resolveExpoSearchResults,
};
