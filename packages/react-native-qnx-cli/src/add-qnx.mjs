import { lstat, readFile, realpath, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { loadExpoConfig } from './expo-config.mjs';
import { validateAppIdentity } from './prepare-native.mjs';

const PLUGIN = '@rn-qnx/expo-qnx-config-plugins';
const checkout = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');

const help = `React Native QNX - add the QNX target to an existing Expo app
  project add-qnx --project <directory> --app-id org.example.notes
                  [--component-name main] [--dry-run]

Adds, and never replaces:
  metro.qnx.config.js   QNX Metro config used by project bundle for qnx
  package.json          "qnx" script and file: links to this checkout's
                        @rn-qnx packages (run your package manager afterwards)
  app.json              the ${PLUGIN} plugin entry with appId and
                        componentName (app.config.js/ts: printed, not edited)

package.json "main", metro.config.js, ios/, android/ and expo.web/platforms
are left as they are, so iOS, Android and web keep working. A rerun with the
same arguments changes nothing. componentName defaults to "main", the name
expo/registerRootComponent registers.
`;

/** @param {string} file */
async function exists(file) {
  try {
    const stat = await lstat(file);
    if (stat.isSymbolicLink()) throw new Error(`${path.basename(file)} must not be a symlink.`);
    return true;
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return false;
    throw error;
  }
}

/**
 * The indentation a JSON file already uses (tab or N spaces), so rewriting it
 * keeps the user's style. Falls back to two spaces.
 * @param {string} text
 */
export function jsonIndent(text) {
  const match = /^[{[][^\S\n]*\n([\t ]+)\S/.exec(text);
  return match ? match[1] : '  ';
}

/** @param {unknown} value @param {string} original */
function formatLike(value, original) {
  return JSON.stringify(value, null, jsonIndent(original)) + (original.endsWith('\n') ? '\n' : '');
}

/** Metro config for the qnx platform that leaves metro.config.js to Expo. */
export function qnxMetroConfigSource() {
  return [
    '// Generated by rnqnx project add-qnx. Used only for --platform qnx bundles;',
    '// metro.config.js stays the config for iOS, Android and web.',
    "const path = require('node:path');",
    "const { createRequire } = require('node:module');",
    "const { getQnxMetroConfig } = require('@rn-qnx/metro-config-qnx');",
    "const withPublicEntry = require('@rn-qnx/metro-config-qnx/public-entry');",
    "const rn = createRequire(require.resolve('react-native/package.json'));",
    'module.exports = withPublicEntry(getQnxMetroConfig(__dirname, {',
    "  resolver: { extraNodeModules: { '@babel/runtime': path.dirname(rn.resolve('@babel/runtime/package.json')) } },",
    "}), 'qnx');",
    '',
  ].join('\n');
}

/**
 * @param {{project: string, appId: string, componentName?: string, dryRun?: boolean}} options
 */
export async function addQnx(options) {
  const root = await realpath(path.resolve(options.project));
  const componentName = options.componentName ?? 'main';
  validateAppIdentity({ appId: options.appId, componentName, displayName: 'placeholder' });
  const manifestPath = path.join(root, 'package.json');
  if (!(await exists(manifestPath))) throw new Error('No package.json; this is not an Expo app.');
  const manifestText = await readFile(manifestPath, 'utf8');
  const manifest = JSON.parse(manifestText);
  if (!manifest.dependencies?.expo)
    throw new Error('package.json does not depend on expo; add-qnx targets existing Expo apps.');
  // Plugins are not run: before the first install the QNX plugin (and any
  // other listed plugin) cannot be resolved, and add-qnx only needs plain
  // fields. A rerun before install therefore behaves like any other rerun.
  const expo = await loadExpoConfig(root, { skipPlugins: true });
  const name = expo.exp.name;
  validateAppIdentity({ appId: options.appId, componentName, displayName: name });

  /** @type {{file: string, action: string, detail?: string}[]} */
  const changes = [];
  /** @type {Map<string, string>} */
  const writes = new Map();

  // 1. metro.qnx.config.js
  const metroPath = path.join(root, 'metro.qnx.config.js');
  const metroSource = qnxMetroConfigSource();
  if (await exists(metroPath)) {
    if ((await readFile(metroPath, 'utf8')) !== metroSource)
      throw new Error('metro.qnx.config.js exists with other contents; review it or remove it.');
    changes.push({ file: 'metro.qnx.config.js', action: 'unchanged' });
  } else {
    writes.set(metroPath, metroSource);
    changes.push({ file: 'metro.qnx.config.js', action: 'created' });
  }

  // 2. package.json: script and local package links. "main" is never touched.
  const bin = path.join(checkout, 'packages/react-native-qnx-cli/src/bin.mjs');
  const wanted = {
    scripts: { qnx: `node ${JSON.stringify(bin)} project run --project .` },
    dependencies: {
      '@rn-qnx/react-native-qnx': `file:${path.join(checkout, 'packages/react-native-qnx')}`,
      '@rn-qnx/metro-config-qnx': `file:${path.join(checkout, 'packages/metro-config-qnx')}`,
      [PLUGIN]: `file:${path.join(checkout, 'packages/expo-qnx-config-plugins')}`,
    },
  };
  const next = { ...manifest };
  for (const [section, entries] of Object.entries(wanted)) {
    next[section] = { ...(manifest[section] ?? {}) };
    for (const [key, value] of Object.entries(entries)) {
      const current = next[section][key];
      if (current !== undefined && current !== value)
        throw new Error(
          `package.json ${section}.${key} is already set to "${current}"; not replacing it.`
        );
      next[section][key] = value;
    }
  }
  const nextText = formatLike(next, manifestText);
  if (JSON.stringify(next) === JSON.stringify(manifest))
    changes.push({ file: 'package.json', action: 'unchanged' });
  else {
    writes.set(manifestPath, nextText);
    changes.push({ file: 'package.json', action: 'updated', detail: 'scripts.qnx, @rn-qnx links' });
  }

  // 3. Plugin entry. Static app.json is edited; dynamic config is app code.
  const pluginOptions = { appId: options.appId, componentName };
  const pluginEntry = [PLUGIN, pluginOptions];
  /** @type {string | null} */
  let manualStep = null;
  if (expo.dynamicConfigPath) {
    // A dynamic config only shows its plugin options once plugins run. Run
    // them when they are installed; before install, fall back to finding the
    // plugin name in the file and say the options are not verified yet.
    /** @type {any} */
    let configured;
    let unverified = false;
    try {
      configured = (await loadExpoConfig(root)).exp.extra?.rnqnx;
    } catch (error) {
      if (!/is not installed/.test(String(/** @type {Error} */ (error).message))) throw error;
      unverified = (await readFile(expo.dynamicConfigPath, 'utf8')).includes(PLUGIN);
    }
    if (unverified)
      changes.push({
        file: path.basename(expo.dynamicConfigPath),
        action: 'unchanged',
        detail: `lists ${PLUGIN}; options are checked after install`,
      });
    else if (configured?.appId === options.appId && configured?.componentName === componentName)
      changes.push({ file: path.basename(expo.dynamicConfigPath), action: 'unchanged' });
    else {
      manualStep = `Add to "plugins" in ${path.basename(expo.dynamicConfigPath)}: ${JSON.stringify(pluginEntry)}`;
      changes.push({
        file: path.basename(expo.dynamicConfigPath),
        action: 'manual',
        detail: manualStep,
      });
    }
  } else {
    const appJsonPath = path.join(root, 'app.json');
    const appJsonText = await readFile(appJsonPath, 'utf8');
    const appJson = JSON.parse(appJsonText);
    const holder = appJson.expo ?? appJson;
    const plugins = Array.isArray(holder.plugins) ? [...holder.plugins] : [];
    const index = plugins.findIndex((p) => p === PLUGIN || (Array.isArray(p) && p[0] === PLUGIN));
    const existing = index >= 0 ? plugins[index] : null;
    const existingOptions = Array.isArray(existing) ? (existing[1] ?? {}) : {};
    for (const [key, value] of Object.entries(pluginOptions))
      if (existingOptions[key] !== undefined && existingOptions[key] !== value)
        throw new Error(
          `The ${PLUGIN} entry already sets ${key} to "${existingOptions[key]}"; not replacing it.`
        );
    const merged = [PLUGIN, { ...existingOptions, ...pluginOptions }];
    if (JSON.stringify(existing) === JSON.stringify(merged))
      changes.push({ file: 'app.json', action: 'unchanged' });
    else {
      if (index >= 0) plugins[index] = merged;
      else plugins.push(merged);
      holder.plugins = plugins;
      writes.set(appJsonPath, formatLike(appJson, appJsonText));
      changes.push({ file: 'app.json', action: index >= 0 ? 'updated' : 'plugin added' });
    }
  }

  if (!options.dryRun) for (const [file, text] of writes) await writeFile(file, text);
  return {
    project: root,
    entry: manifest.main ?? 'index.js',
    dryRun: !!options.dryRun,
    changes,
    manualStep,
    next: [
      'Install dependencies with your package manager.',
      ...(manualStep ? [manualStep] : []),
      'Develop with Expo CLI as usual: npx expo start.',
      'Build and run on QNX: node --run qnx (pnpm qnx).',
    ],
  };
}

/** @param {string[]} argv */
export async function addQnxMain(argv) {
  const { values, positionals } = parseArgs({
    args: argv,
    strict: true,
    allowPositionals: true,
    options: {
      help: { type: 'boolean', short: 'h' },
      project: { type: 'string' },
      'app-id': { type: 'string' },
      'component-name': { type: 'string' },
      'dry-run': { type: 'boolean' },
    },
  });
  if (values.help || argv.length === 0) {
    console.log(help);
    return 0;
  }
  if (positionals.length) throw new Error('add-qnx accepts no positional arguments.');
  if (!values['app-id']) throw new Error('add-qnx needs --app-id, for example org.example.notes.');
  const result = await addQnx({
    project: values.project ?? '.',
    appId: values['app-id'],
    componentName: values['component-name'],
    dryRun: values['dry-run'],
  });
  console.log(JSON.stringify(result, null, 2));
  return 0;
}
